/**
 * Секции прочности вдоль корпуса, от носа к корме. Урон заливает секции с носа: нос смотрит на
 * врага и получает первым — так читается, куда пришлись попадания.
 */
export function hullSections(type: ShipType, hull: number): { y: number; height: number }[] {
  const sprite = BATTLE_SPRITES[type]
  const count = Math.max(1, hull)
  const span = (sprite.bottom - sprite.top) / count
  return Array.from({ length: count }, (_, i) => ({ y: sprite.top + i * span, height: span }))
}
